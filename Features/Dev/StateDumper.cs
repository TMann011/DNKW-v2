    public static class StateDumper
    {
        public static string GetDumpFilePath()
        {
            try
            {
                string desktopPath = Environment.GetFolderPath(Environment.SpecialFolder.Desktop);
                if (!string.IsNullOrEmpty(desktopPath) && Directory.Exists(desktopPath))
                {
                    return Path.Combine(desktopPath, "dnkw_dump.txt");
                }
            }
            catch { }

            string baseDir = Path.Combine(AppDomain.CurrentDomain.BaseDirectory, "UserData");
            if (!Directory.Exists(baseDir)) Directory.CreateDirectory(baseDir);
            return Path.Combine(baseDir, "dnkw_dump.txt");
        }

        public static string DumpStateToDesktop()
        {
            try
            {
                string filePath = GetDumpFilePath();

                StringBuilder sb = new StringBuilder();
                sb.AppendLine("=================================================================");
                sb.AppendLine("      DEATH NOTE Killer Within - Live Game State & Lobby Dump");
                sb.AppendLine("      Generated by Inkwell (Cheat v3.0)");
                sb.AppendLine($"      Timestamp: {DateTime.Now:yyyy-MM-dd HH:mm:ss}");
                sb.AppendLine("=================================================================");
                sb.AppendLine();

                GameStateManager gsm = EngineStrictSingleton<GameStateManager>.Instance;
                if (gsm == null)
                {
                    sb.AppendLine("[!] GameStateManager is currently NULL (In Main Menu / Lobby Scene).");
                    sb.AppendLine("------------------ LOBBY & SCENE ENTITY INSPECTION ------------------");

                    PlayerMovement[] scenePlayers = UnityEngine.Object.FindObjectsOfType<PlayerMovement>();
                    if (scenePlayers != null && scenePlayers.Length > 0)
                    {
                        sb.AppendLine($"[+] Discovered {scenePlayers.Length} PlayerMovement entities in scene:");
                        for (int i = 0; i < scenePlayers.Length; i++)
                        {
                            var p = scenePlayers[i];
                            if (p == null) continue;
                            string name = p.GetPlayerName(false, true);
                            sb.AppendLine($"   [{i + 1}] Actor #{p.ActorID} | Name: '{name}' | Pos: {p.GetPosition()} | Dead: {p.IsDead}");
                        }
                    }
                    else
                    {
                        sb.AppendLine("[-] No PlayerMovement instances active in main menu scene.");
                    }
                }
                else
                {
                    sb.AppendLine($"[+] Match State: {gsm.State}");
                    sb.AppendLine($"[+] Current Day: {gsm.CurrentDay}, Field Phase: {gsm.IsFieldPhase}, Game Over: {GameStateManager.IsGameOver}");
                    sb.AppendLine($"[+] Winner: {gsm.Winner}, Reason: {gsm.WinReason}");

                    PlayerMovement myPlayer = gsm.MyPlayer;
                    if (myPlayer != null)
                    {
                        sb.AppendLine($"[+] Local Player: #{myPlayer.ActorID} '{myPlayer.GetPlayerName(false, true)}'");
                        sb.AppendLine($"    Role: {myPlayer.Role} ({myPlayer.RoleDetail})");
                        sb.AppendLine($"    Position: {myPlayer.GetPosition()}");
                        sb.AppendLine($"    Dead: {myPlayer.IsDead}, Spectating: {myPlayer.IsSpectating}");
                        sb.AppendLine($"    Has Death Note: {myPlayer.HasDeathNote}, Has Stolen ID: {myPlayer.HasOthersID}");
                    }

                    sb.AppendLine();
                    sb.AppendLine("------------------ ACTIVE PLAYERS ROSTER ------------------");
                    if (gsm.PlayerList != null)
                    {
                        var enumerator = gsm.PlayerList.GetEnumerator();
                        int index = 0;
                        while (enumerator.MoveNext())
                        {
                            PlayerMovement p = enumerator.Current;
                            if (p == null) continue;

                            index++;
                            bool isSelf = myPlayer != null && p.ActorID == myPlayer.ActorID;
                            string name = p.GetPlayerName(false, true);
                            string role = p.GetRoleName(false, true);
                            Vector3 pos = p.GetPosition();

                            sb.AppendLine($"[{index}] Player: #{p.ActorID} '{name}' {(isSelf ? "[YOU]" : "")}");
                            sb.AppendLine($"     Role: {role} (Enum: {p.RoleDetail})");
                            sb.AppendLine($"     Status: {(p.IsDead ? "DEAD" : "ALIVE")}, Spectating: {p.IsSpectating}, Arrested: {p.IsArrested}");
                            sb.AppendLine($"     World Position: ({pos.x:F2}, {pos.y:F2}, {pos.z:F2})");
                            sb.AppendLine($"     Inventory: DeathNote={p.HasDeathNote}, StolenID={p.HasOthersID}, Transceiver={p.IsUsingTransceiver}");
                        }
                    }
                    else
                    {
                        sb.AppendLine("[-] PlayerList is null.");
                    }
                }

                sb.AppendLine();
                sb.AppendLine("------------------ TYPE REFLECTION INSPECTION ------------------");
                try
                {
                    var appClientType = Il2CppInterop.Runtime.Il2CppType.Of<AppClient>();
                    if (appClientType != null)
                    {
                        sb.AppendLine($"=== Methods on {appClientType.FullName} ===");
                        foreach (var m in appClientType.GetMethods()) sb.AppendLine($"  [M] {m.Name}");
                    }
                    var mmType = Il2CppInterop.Runtime.Il2CppType.Of<Il2CppLunaOutGame.MatchmakerObject>();
                    if (mmType != null)
                    {
                        sb.AppendLine($"=== Methods on {mmType.FullName} ===");
                        foreach (var m in mmType.GetMethods()) sb.AppendLine($"  [M] {m.Name}");
                    }
                    var roomType = Il2CppInterop.Runtime.Il2CppType.Of<Il2CppLunaOutGame.RoomScene>();
                    if (roomType != null)
                    {
                        sb.AppendLine($"=== Methods on {roomType.FullName} ===");
                        foreach (var m in roomType.GetMethods()) sb.AppendLine($"  [M] {m.Name}");
                    }
                }
                catch (Exception ex)
                {
                    sb.AppendLine($"[-] Reflection dump error: {ex.Message}");
                }

                File.WriteAllText(filePath, sb.ToString());
                MelonLogger.Msg($"[+] Successfully dumped game state to: {filePath}");
                return filePath;
            }
            catch (Exception ex)
            {
                MelonLogger.Error($"[-] Failed to dump game state: {ex.Message}");
                return $"Error: {ex.Message}";
            }
        }

