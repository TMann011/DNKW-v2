        public static void DrawDebugHud()
        {
            if (!Config.ShowDebugOverlay) return;

            try
            {
                float w = 340f;
                float h = 260f;
                Rect r = new Rect(20f, Screen.height - h - 30f, w, h);

                GUI.backgroundColor = new Color(0.02f, 0.04f, 0.08f, 0.92f);
                GUI.Box(r, "<b><color=#00DDFF>[INKWELL LIVE DEBUG TELEMETRY]</color></b>");

                StringBuilder sb = new StringBuilder();

                GameStateManager gsm = EngineStrictSingleton<GameStateManager>.Instance;
                if (gsm != null)
                {
                    sb.AppendLine($"<color=#55FFAA>GameState:</color> {gsm.State}");
                    sb.AppendLine($"<color=#55FFAA>Day:</color> {gsm.CurrentDay} | <color=#55FFAA>Field:</color> {gsm.IsFieldPhase} | <color=#55FFAA>Over:</color> {GameStateManager.IsGameOver}");
                    if (gsm.MyPlayer != null)
                    {
                        PlayerMovement p = gsm.MyPlayer;
                        Vector3 pos = p.GetPosition();
                        sb.AppendLine($"<color=#00FFB0>Local Player:</color> #{p.ActorID} '{p.GetPlayerName(false, true)}'");
                        sb.AppendLine($"<color=#00FFB0>Role:</color> {p.Role} ({p.RoleDetail})");
                        sb.AppendLine($"<color=#00FFB0>Pos:</color> ({pos.x:F1}, {pos.y:F1}, {pos.z:F1})");
                        sb.AppendLine($"<color=#00FFB0>State:</color> Dead={p.IsDead}, DN={p.HasDeathNote}, ID={p.HasOthersID}");
                    }
                }
                else
                {
                    sb.AppendLine("<color=#FF8800>GameStateManager:</color> NULL (Lobby Scene)");
                    var scenePlayers = UnityEngine.Object.FindObjectsOfType<PlayerMovement>();
                    int pCount = scenePlayers != null ? scenePlayers.Length : 0;
                    sb.AppendLine($"<color=#00DDFF>Scene Players:</color> {pCount}");
                }

                Il2CppLunaOutGame.RoomScene? roomScene = null;
                GameObject roomSceneObj = GameObject.Find("RoomSceneRoot");
                if (roomSceneObj != null) roomScene = roomSceneObj.GetComponent<Il2CppLunaOutGame.RoomScene>();

                if (roomScene != null && roomScene.Matchmaker != null && roomScene.Matchmaker.playerList != null)
                {
                    sb.AppendLine($"<color=#FFD700>Lobby Roster:</color> {roomScene.Matchmaker.playerList.Count} connected");
                }

                sb.AppendLine($"<color=#888888>FPS: {(1.0f / Time.smoothDeltaTime):F0} | AntiKick: {Config.AntiKickProtection}</color>");

                GUI.Label(new Rect(r.x + 10f, r.y + 24f, r.width - 20f, r.height - 28f), sb.ToString());
            }
            catch { }
        }
    }
